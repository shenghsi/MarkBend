// @vitest-environment jsdom
import { expect, it, vi } from 'vitest';
import { undoDepth } from '@codemirror/commands';
import { normalize, savedSource, sourceField } from '../../src/web/source';
const mocks = vi.hoisted(() => ({ invoke: vi.fn(), open: vi.fn(), save: vi.fn(), ask: vi.fn() }));
vi.mock('@tauri-apps/api/core', () => ({ invoke: mocks.invoke, isTauri: () => true }));
vi.mock('@tauri-apps/plugin-dialog', () => ({ ask: mocks.ask, open: mocks.open, save: mocks.save }));
vi.mock('@tauri-apps/api/window', () => ({ getCurrentWindow: () => ({ onDragDropEvent: async () => vi.fn(), onCloseRequested: vi.fn(), listen: vi.fn() }) }));
it('keeps current source on file warnings and failed Reload then starts new exact history on accepted Reload', async () => {
  let disk = '\uFEFFa\rb\r\nEnd', failRead = false, failCheckpoint = false, uncertainSave = false;
  let observation = { kind: 'changed', generation: 1 };
  const calls = (command: string) => mocks.invoke.mock.calls.filter(([name]) => name === command);
  mocks.invoke.mockImplementation(async (command: string) => {
    if (command === 'recovery_start' || command === 'recovery_list') return { session: 'session-test', revision: 0, entries: [], warnings: [] };
    if (command === 'recovery_checkpoint' && failCheckpoint) throw 'checkpoint failed';
    if (command === 'open_document') { if (failRead) throw 'read failed'; return { path: '/tmp/changed.md', source: disk }; }
    if (command === 'file_status') return observation;
    if (command === 'save_document' && uncertainSave) throw { uncertain: true, message: 'sync failed' };
  });
  mocks.open.mockResolvedValue('/tmp/changed.md'); mocks.save.mockResolvedValue('/tmp/new-copy.md'); mocks.ask.mockResolvedValue(true);
  document.body.innerHTML = '<div id="app"></div>';
  const { view } = await import('../../src/web/main');
  const source = () => savedSource(view.state.field(sourceField));
  document.querySelector<HTMLButtonElement>('#open')!.click();
  await vi.waitFor(() => { expect(source()).toBe(disk); expect(view.state.readOnly).toBe(false); });
  view.dispatch({ changes: { from: view.state.doc.length, insert: ' draft' } });
  const original = source(), depth = undoDepth(view.state);
  document.querySelector<HTMLButtonElement>('#check-file')!.click();
  await vi.waitFor(() => expect(document.querySelector('.file-warning')!.textContent).toContain('file changed on disk'));
  expect(source()).toBe(original); expect(undoDepth(view.state)).toBe(depth);
  const reload = () => document.querySelector<HTMLButtonElement>('.file-warning button')!.click();
  mocks.ask.mockResolvedValueOnce(false); reload();
  await vi.waitFor(() => { expect(mocks.ask).toHaveBeenCalled(); expect(view.state.readOnly).toBe(false); });
  expect(source()).toBe(original); expect(calls('open_document')).toHaveLength(1);
  failCheckpoint = true; reload();
  await vi.waitFor(() => expect(document.querySelector('#status')!.textContent).toContain('checkpoint failed'));
  expect(source()).toBe(original); expect(calls('open_document')).toHaveLength(1);
  failCheckpoint = false; failRead = true; reload();
  await vi.waitFor(() => expect(document.querySelector('#status')!.textContent).toContain('read failed'));
  expect(source()).toBe(original); expect(undoDepth(view.state)).toBe(depth);
  failRead = false; disk = '\uFEFF日本語😀\r\nexternal\rtail\n'; reload();
  await vi.waitFor(() => { expect(source()).toBe(disk); expect(view.state.readOnly).toBe(false); });
  expect(view.state.doc.toString()).toBe(normalize(disk.slice(1))); expect(undoDepth(view.state)).toBe(0);
  expect(document.querySelector('#status')!.textContent).toBe('changed.md');
  expect((document.querySelector('.file-warning') as HTMLElement).hidden).toBe(true);
  view.contentDOM.dispatchEvent(new CompositionEvent('compositionstart', { bubbles: true }));
  const count = calls('file_status').length; document.querySelector<HTMLButtonElement>('#check-file')!.click();
  expect(calls('file_status')).toHaveLength(count);
  view.contentDOM.dispatchEvent(new CompositionEvent('compositionend', { bubbles: true }));
  uncertainSave = true; document.querySelector<HTMLButtonElement>('#save-as')!.click();
  await vi.waitFor(() => expect(document.querySelector('#status')!.textContent).toContain('uncertain'));
  const controls = document.querySelectorAll<HTMLButtonElement>('.file-warning button');
  expect(controls[0].disabled).toBe(true); expect(controls[1].disabled).toBe(true);
  const opens = calls('open_document').length; reload(); expect(calls('open_document')).toHaveLength(opens);
  observation = { kind: 'unchanged', generation: 2 };
  document.querySelector<HTMLButtonElement>('#check')!.click();
  await vi.waitFor(() => expect(document.querySelector('#status')!.textContent).toBe('new-copy.md'));
  expect((document.querySelector('.file-warning') as HTMLElement).hidden).toBe(true);
  window.dispatchEvent(new Event('pagehide')); view.destroy();
});
